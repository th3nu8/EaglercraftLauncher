#!/usr/bin/env node
/* Builds launcher/specs.js and the generated block in server/server.js from tools/game-achievements.json.
 * Each game: { "spec": { src, key, fmt, stats, ... }, "ach": [[id, icon, name, desc, stat, goal, rank], ...] }
 * A key written as "/regex/" becomes a RegExp. Run: node tools/build-achievements.js */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(__dirname, 'game-achievements.json'), 'utf8'));
const RANKS = ['common', 'rare', 'epic', 'legendary'];
let specs = [], defs = [], problems = [];
for (const [game, g] of Object.entries(data)) {
  if (game.startsWith('_')) continue;
  const sp = g.spec, stats = new Set(Object.keys(sp.stats || {}));
  const key = typeof sp.key === 'string' && /^\/.*\/[a-z]*$/.test(sp.key) ? sp.key : JSON.stringify(sp.key);
  const rest = Object.assign({}, sp); delete rest.key;
  specs.push(`  ${JSON.stringify(game)}: Object.assign(${JSON.stringify(rest)}, { key: ${key} })`);
  const ids = new Set();
  for (const a of g.ach) {
    const [id, icon, name, desc, stat, goal, rank] = a;
    if (!stats.has(stat)) problems.push(`${game}: ${id} uses unknown stat ${stat}`);
    if (!RANKS.includes(rank)) problems.push(`${game}: ${id} bad rank ${rank}`);
    if (ids.has(id)) problems.push(`${game}: duplicate id ${id}`); ids.add(id);
  }
  defs.push(`  ${JSON.stringify(game)}: [\n` + g.ach.map(([id, icon, name, desc, stat, goal, rank]) =>
    `    { id: ${JSON.stringify(id)}, icon: ${JSON.stringify(icon)}, name: ${JSON.stringify(name)}, desc: ${JSON.stringify(desc)}, stat: ${JSON.stringify(stat)}, goal: ${goal}, rank: ${JSON.stringify(rank)} },`).join('\n') + '\n  ],');
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
fs.writeFileSync(path.join(root, 'launcher/specs.js'),
  '/* Generated by tools/build-achievements.js from tools/game-achievements.json - edit that file instead. */\nwindow.MIST_SPECS = {\n' + specs.join(',\n') + '\n};\n');
const sf = path.join(root, 'server/server.js'); let s = fs.readFileSync(sf, 'utf8');
const A = '/* GENERATED-ACHIEVEMENTS-START */', B = '/* GENERATED-ACHIEVEMENTS-END */';
const block = A + '\n// Generated by tools/build-achievements.js from tools/game-achievements.json - edit that file instead.\nObject.assign(HOOK_ACH, {\n' + defs.join('\n') + '\n});\n' + B;
if (s.includes(A)) s = s.slice(0, s.indexOf(A)) + block + s.slice(s.indexOf(B) + B.length);
else { const anchor = 'for (const [g, defs] of Object.entries(HOOK_ACH)) for (const a of defs) if (!a.rank)'; s = s.replace(anchor, block + '\n' + anchor); }
fs.writeFileSync(sf, s);
console.log(`Built ${specs.length} games, ${defs.reduce((n, d) => n + (d.match(/\{ id:/g) || []).length, 0)} achievements.`);
